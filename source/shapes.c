// Shape data functions

ShapeData ShapeData_init() {
   ShapeData data;
   data.verticeCount = 0;
   data.lineCount = 0;
   data.triangleCount = 0;
   data.vertices = NULL;
   data.lines = NULL;
   data.triangles = NULL;
   data.points = NULL;
   data.origin = (Vector3){0.0f, 0.0f, 0.0f};
   return data;
}

void ShapeData_free(ShapeData *data) {
   if (data->points) {
      free(data->points);
   }
}

